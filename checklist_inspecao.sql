-- Esquema para PostgreSQL. Execute no banco que deseja usar.

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_uid UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  nome_de_usuario VARCHAR(60) NOT NULL UNIQUE,
  tipo_de_perfil VARCHAR(10) NOT NULL DEFAULT 'operador'
    CHECK (tipo_de_perfil IN ('operador', 'gerente')),
  data_de_criacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS veiculos (
  id_veiculo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nome_modelo VARCHAR(60) NOT NULL,
  placa VARCHAR(10) NOT NULL UNIQUE,
  pressao_minima_psi NUMERIC(5,1) NOT NULL,
  pressao_maxima_psi NUMERIC(5,1) NOT NULL,
  situacao VARCHAR(10) NOT NULL DEFAULT 'liberado'
    CHECK (situacao IN ('liberado', 'bloqueado')),
  data_de_criacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT verificar_faixa_de_pressao
    CHECK (pressao_minima_psi < pressao_maxima_psi)
);

CREATE TABLE IF NOT EXISTS inspecoes (
  id_inspecao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_veiculo BIGINT NOT NULL REFERENCES veiculos(id_veiculo),
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
  data_da_inspecao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resultado VARCHAR(10) NOT NULL
    CHECK (resultado IN ('regular', 'irregular', 'pendente')),
  veiculo_bloqueado BOOLEAN NOT NULL DEFAULT FALSE,
  observacoes TEXT
);

CREATE TABLE IF NOT EXISTS itens_inspecao (
  id_item_inspecao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_inspecao BIGINT NOT NULL REFERENCES inspecoes(id_inspecao)
    ON DELETE CASCADE,
  categoria VARCHAR(40) NOT NULL,
  nome_item VARCHAR(150) NOT NULL,
  valor VARCHAR(100),
  resultado VARCHAR(10) NOT NULL DEFAULT 'pendente'
    CHECK (resultado IN ('regular', 'irregular', 'pendente')),
  item_critico BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS indice_inspecoes_data
  ON inspecoes (data_da_inspecao);
CREATE INDEX IF NOT EXISTS indice_inspecoes_veiculo
  ON inspecoes (id_veiculo);
CREATE INDEX IF NOT EXISTS indice_itens_categoria
  ON itens_inspecao (categoria);
CREATE INDEX IF NOT EXISTS indice_itens_resultado
  ON itens_inspecao (resultado);

