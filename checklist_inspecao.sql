ALTER TABLE usuarios DROP COLUMN IF EXISTS senha_criptografada;
CREATE UNIQUE INDEX IF NOT EXISTS indice_usuarios_auth_uid ON usuarios (auth_uid);

CREATE OR REPLACE FUNCTION criar_perfil_de_usuario()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.usuarios (auth_uid, nome_de_usuario, tipo_de_perfil)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data ->> 'nome_de_usuario', split_part(NEW.email, '@', 1)),
    'operador'
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS ao_criar_usuario_auth ON auth.users;
CREATE TRIGGER ao_criar_usuario_auth
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION criar_perfil_de_usuario();

CREATE OR REPLACE FUNCTION alterar_situacao_veiculo(codigo_veiculo VARCHAR, nova_situacao VARCHAR)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'É necessário entrar no sistema.';
  END IF;
  IF nova_situacao NOT IN ('liberado', 'bloqueado') THEN
    RAISE EXCEPTION 'Situação de veículo inválida.';
  END IF;
  UPDATE public.veiculos SET situacao = nova_situacao WHERE codigo = codigo_veiculo;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Veículo não encontrado.';
  END IF;
END;
$$;

GRANT EXECUTE ON FUNCTION alterar_situacao_veiculo(VARCHAR, VARCHAR) TO authenticated;

